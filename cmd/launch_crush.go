package cmd

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"mvdan.cc/sh/v3/syntax"
)

// crushLaunchSpec builds Crush's environment for a sandboxed run. Crush has no
// command-line flag or environment variable that adds configuration, only
// CRUSH_GLOBAL_CONFIG, which moves its whole global config directory. So
// launch points it at a directory of its own (launchCacheDir) that stands in
// for the user's:
//
//   - crush.json is a symlink to the user's global crush.json, if any;
//   - crushrc changes into the user's config directory and sources their
//     global crushrc, if any, so it runs as it would without the launch, then
//     adds the sandbox's rules (crushRCRules, as `install crush` writes them);
//   - the global context paths are set to the user's CRUSH.md and the AGENTS.md
//     beside their config directory (Crush's defaults, which it would otherwise
//     look for beside this directory) plus a file with the usage directive.
//
// Crush's data directory (CRUSH_GLOBAL_DATA), skills, and commands are found
// independently of CRUSH_GLOBAL_CONFIG, and project configs still load.
func crushLaunchSpec(binPath string, agentArgs []string) (launchSpec, error) {
	if out, err := crushVersionOutput(); err == nil && !crushVersionSupportsRC(out) {
		return launchSpec{}, fmt.Errorf("launch crush needs crush v0.88.0 or newer (for crushrc); found %s", strings.TrimSpace(out))
	}
	userDir, err := crushConfigDir()
	if err != nil {
		return launchSpec{}, err
	}
	dir, err := launchCacheDir("crush")
	if err != nil {
		return launchSpec{}, err
	}
	if sameDir(userDir, dir) {
		// A launch from inside a launched Crush: sourcing would recurse.
		return launchSpec{}, fmt.Errorf("CRUSH_GLOBAL_CONFIG already points at launch's own directory %s; unset it to launch Crush", dir)
	}

	directivePath := filepath.Join(dir, "lite-sandbox.md")
	if err := writeFileAtomic(directivePath, []byte(crushDirective+"\n")); err != nil {
		return launchSpec{}, fmt.Errorf("failed to write %s: %w", directivePath, err)
	}
	if err := linkCrushJSON(filepath.Join(userDir, "crush.json"), filepath.Join(dir, "crush.json")); err != nil {
		return launchSpec{}, err
	}
	rc, err := crushLaunchRC(binPath, userDir, directivePath)
	if err != nil {
		return launchSpec{}, err
	}
	rcPath := filepath.Join(dir, "crushrc")
	if err := writeFileAtomic(rcPath, []byte(rc)); err != nil {
		return launchSpec{}, fmt.Errorf("failed to write %s: %w", rcPath, err)
	}
	return launchSpec{
		args: agentArgs,
		env:  []string{"CRUSH_GLOBAL_CONFIG=" + dir},
	}, nil
}

// crushLaunchRC renders the stand-in global crushrc.
func crushLaunchRC(binPath, userDir, directivePath string) (string, error) {
	quote := func(s string) (string, error) {
		q, err := syntax.Quote(s, syntax.LangBash)
		if err != nil {
			return "", fmt.Errorf("cannot quote %q for crushrc: %w", s, err)
		}
		return q, nil
	}
	var b strings.Builder
	b.WriteString("# Generated by `lite-sandbox launch crush` on every launch; edits are overwritten.\n")
	if fileExists(filepath.Join(userDir, "crushrc")) {
		q, err := quote(userDir)
		if err != nil {
			return "", err
		}
		// Crush runs a crushrc from its own directory; do the same for theirs.
		b.WriteString("cd " + q + " && source ./crushrc\n")
	}
	rules, err := crushRCRules(binPath)
	if err != nil {
		return "", err
	}
	b.WriteString(rules)
	for _, p := range []string{
		filepath.Join(userDir, "CRUSH.md"),
		filepath.Join(filepath.Dir(userDir), "AGENTS.md"),
		directivePath,
	} {
		q, err := quote(p)
		if err != nil {
			return "", err
		}
		b.WriteString("option global-context-path " + q + "\n")
	}
	return b.String(), nil
}

// linkCrushJSON makes link a symlink to the user's crush.json, or removes it
// when the user has none. The link is created beside its final name and
// renamed into place, so a concurrent launch never sees it missing.
func linkCrushJSON(target, link string) error {
	if !fileExists(target) {
		if err := os.Remove(link); err != nil && !os.IsNotExist(err) {
			return fmt.Errorf("failed to remove %s: %w", link, err)
		}
		return nil
	}
	tmp := fmt.Sprintf("%s.%d.tmp", link, os.Getpid())
	os.Remove(tmp)
	if err := os.Symlink(target, tmp); err != nil {
		return fmt.Errorf("failed to link %s: %w", target, err)
	}
	if err := os.Rename(tmp, link); err != nil {
		os.Remove(tmp)
		return fmt.Errorf("failed to link %s: %w", target, err)
	}
	return nil
}

// sameDir reports whether a and b name the same directory, comparing resolved
// paths when they exist.
func sameDir(a, b string) bool {
	if ra, err := filepath.EvalSymlinks(a); err == nil {
		a = ra
	}
	if rb, err := filepath.EvalSymlinks(b); err == nil {
		b = rb
	}
	return filepath.Clean(a) == filepath.Clean(b)
}
